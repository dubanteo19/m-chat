CREATE TABLE sticker_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    owner_id BIGINT NOT NULL,

    name VARCHAR(50) NOT NULL,
    description VARCHAR(500),

    visibility VARCHAR(20) NOT NULL DEFAULT 'PRIVATE',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sticker_package_owner
        FOREIGN KEY (owner_id)
        REFERENCES chat_users(id),

    CONSTRAINT chk_sticker_package_visibility
        CHECK (visibility IN ('PRIVATE', 'PUBLIC')),

    CONSTRAINT chk_sticker_package_status
        CHECK (status IN ('DRAFT', 'PUBLISHED'))
);

CREATE INDEX idx_sticker_packages_owner
    ON sticker_packages(owner_id);


CREATE TABLE stickers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    package_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',

    image_key VARCHAR(500),

    width INTEGER,
    height INTEGER,
    file_size BIGINT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sticker_package
        FOREIGN KEY (package_id)
        REFERENCES sticker_packages(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_sticker_status
        CHECK (status IN ('PROCESSING', 'READY', 'FAILED'))
);

CREATE INDEX idx_stickers_package
    ON stickers(package_id);